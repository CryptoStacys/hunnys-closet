// Initialize ethers
const provider = new ethers.providers.JsonRpcProvider(providerUrl);
const wallet = new ethers.Wallet(privateKey, provider);
const contract = new ethers.Contract(contractAddress, contractAbi, wallet);


async function main() {
    console.log('Starting the script...');// Check provider connection
    try {
        const blockNumber = await provider.getBlockNumber();
        console.log('Connected to the network at block number:', blockNumber);
    } catch (error) {
        console.error('Failed to connect to the network:', error);
        return;
    }

    const baseUri = 'https://hunnysseasons.s3.us-east-2.amazonaws.com/';

    let nonce = await provider.getTransactionCount(wallet.address, 'latest'); // Get current nonce

    for (let tokenId = 1; tokenId <= 4; tokenId++) {
        const tokenUri = `${baseUri}${tokenId}.json`;
        console.log(`Attempting to update token ${tokenId}`);
        try {
            await updateTokenUri(tokenId, tokenUri, nonce++);
            // Consider adding a delay here if needed
        } catch (error) {
            console.error(`Error updating token ${tokenId}:`, error);
        }
    }
}

async function updateTokenUri(tokenId, newUri, _nonce) {
    console.log(`Sending transaction to update token ${tokenId}`);
    try {
        const tx = await contract.updateUri(tokenId, newUri, {
            gasLimit: ethers.utils.hexlify(500000), // Example gas limit, adjust as needed
            gasPrice: ethers.utils.hexlify(300000000000), // Example gas price, adjust as needed
            nonce: 26689
        });
        console.log(`Transaction sent, waiting for confirmation. Hash: ${tx.hash}`);
        await tx.wait();
        console.log(`Updated token ${tokenId} with URI ${newUri}`);
    } catch (error) {
        console.error(`Error in transaction for token ${tokenId}:`, error);
    }
}

main().then(() => console.log('Update process completed.'))
    .catch((error) => console.error(`Failed to run the script: ${error}`));
