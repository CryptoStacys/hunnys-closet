const skin = [];
export default async function detectColor() {
  let output: any = {};
  for (let i = 0; i < colors.length; i++) {
    // load image
    const img = new Image();
    img.src = `${layersPath}Colors/ClothingAndHair/Solid/${colors[i]}`;

    // built in promise, wait until loaded
    await img.decode();

    // create virtual canvas
    const canvas = document.createElement("canvas");
    canvas.width = 300;
    canvas.height = 300;
    const context = canvas.getContext("2d");

    // draw image on canvas
    context!.drawImage(img, 0, 0);
    const imgData = context!.getImageData(0, 0, canvas.width, canvas.height);

    output[colors[i].split(".")[0]] = {
      r: imgData.data[0],
      g: imgData.data[1],
      b: imgData.data[2],
    };
  }
  console.log(output);
}
